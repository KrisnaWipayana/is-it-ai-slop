#!/usr/bin/env node
/**
 * Synchronizes `.env` values into `extension/env.js` for the browser extension.
 */

const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const envPath = path.join(rootDir, '.env');
const targetPath = path.join(rootDir, 'extension', 'env.js');

const envVars = {
  TYPESAFE_API_KEY: '',
  JEV_API_URL: 'https://api.typesafe.ai/v1/systemone',
  JEV_MODEL: 'jev-latest',
  JEV_MAX_WORDS_PER_CALL: 150
};

if (fs.existsSync(envPath)) {
  const content = fs.readFileSync(envPath, 'utf8');
  const lines = content.split('\n');

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;

    const eqIdx = trimmed.indexOf('=');
    if (eqIdx !== -1) {
      const key = trimmed.slice(0, eqIdx).trim();
      let val = trimmed.slice(eqIdx + 1).trim();

      // Remove wrapping quotes if present
      if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
        val = val.slice(1, -1);
      }

      if (key in envVars) {
        if (key === 'JEV_MAX_WORDS_PER_CALL') {
          envVars[key] = parseInt(val, 10) || 150;
        } else {
          envVars[key] = val;
        }
      }
    }
  }
}

const fileContent = `/**
 * Is It AI Slop? - Environment Configuration
 * Auto-generated by scripts/sync-env.js from .env
 * You can also set/override your TypeSafe AI API key directly via the extension Popup settings.
 */
(function () {
  'use strict';

  const defaultEnv = ${JSON.stringify(envVars, null, 2)};

  if (typeof window !== 'undefined') {
    window.ENV = Object.assign({}, defaultEnv, window.ENV || {});
  } else if (typeof globalThis !== 'undefined') {
    globalThis.ENV = Object.assign({}, defaultEnv, globalThis.ENV || {});
  }
})();
`;

fs.writeFileSync(targetPath, fileContent, 'utf8');
console.log(`Successfully synced .env to ${targetPath}`);
